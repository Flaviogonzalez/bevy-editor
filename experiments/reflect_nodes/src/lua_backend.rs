//! The Lua preview: generated glue that calls the Rust nodes through reflection.
//!
//! The glue never does arithmetic itself. Every operation is a call into the same compiled Rust
//! function the Rust backend uses, so node behavior can't drift between the two.

use std::fmt::Write as _;
use std::rc::Rc;

use bevy_reflect::PartialReflect;
use bevy_reflect::func::FunctionRegistry;
use bevy_reflect::func::args::ArgList;
use mlua::{Function, Lua, Variadic};

use crate::catalog::{NodeSpec, PinType};
use crate::ir::{Operand, Program, Value};

/// Lua source for a program: a chunk that returns the program as a function.
pub fn emit(program: &Program) -> String {
    let params: Vec<String> = (0..program.inputs.len()).map(|i| format!("in{i}")).collect();
    let mut out = format!("return function({})\n", params.join(", "));
    for call in &program.calls {
        let args: Vec<String> = call.args.iter().map(operand).collect();
        let _ = writeln!(out, "    local v{} = node.{}({})", call.var, call.node, args.join(", "));
    }
    let _ = write!(out, "    return {}\nend\n", operand(&program.result));
    out
}

fn operand(op: &Operand) -> String {
    match op {
        Operand::Input(i) => format!("in{i}"),
        Operand::Var(v) => format!("v{v}"),
        Operand::Number(n) => number(*n),
        Operand::Bool(b) => b.to_string(),
        Operand::Text(t) => format!("{t:?}"),
    }
}

/// An f32 written so Lua reads back exactly the same value.
fn number(n: f32) -> String {
    if n.is_nan() {
        "(0/0)".into()
    } else if n.is_infinite() {
        if n > 0.0 { "math.huge".into() } else { "(-math.huge)".into() }
    } else {
        // Every f32 is exactly representable as f64, and `{:?}` prints the shortest text that
        // round-trips, so the literal is exact.
        format!("{:?}", n as f64)
    }
}

/// A Lua state whose `node` table holds typed bindings generated by `nodes!`: the same Rust
/// functions, without reflection on each call.
pub fn runtime_typed() -> mlua::Result<Lua> {
    let lua = Lua::new();
    let node = crate::nodes::lua_table(&lua)?;
    lua.globals().set("node", node)?;
    Ok(lua)
}

/// A Lua state with a `node` table: one function per catalog entry, each calling the registry.
pub fn runtime(registry: Rc<FunctionRegistry>, catalog: &[NodeSpec]) -> mlua::Result<Lua> {
    let lua = Lua::new();
    let node = lua.create_table()?;
    for spec in catalog {
        let registry = registry.clone();
        let spec = spec.clone();
        let name = spec.name.clone();
        node.set(
            name,
            lua.create_function(move |lua, args: Variadic<mlua::Value>| {
                let mut list = ArgList::default();
                for (value, (arg, ty)) in args.iter().zip(&spec.inputs) {
                    match (ty, value) {
                        (PinType::Number, mlua::Value::Number(n)) => list.push_owned(*n as f32),
                        (PinType::Number, mlua::Value::Integer(n)) => list.push_owned(*n as f32),
                        (PinType::Bool, mlua::Value::Boolean(b)) => list.push_owned(*b),
                        (PinType::Text, mlua::Value::String(s)) => list.push_owned(s.to_str()?.to_string()),
                        _ => {
                            return Err(mlua::Error::runtime(format!(
                                "{}: argument `{arg}` should be {ty:?}, got {}",
                                spec.name,
                                value.type_name()
                            )));
                        }
                    }
                }
                let result = registry
                    .call(&spec.name, list)
                    .expect("catalog entries come from the registry")
                    .map_err(|e| mlua::Error::runtime(format!("{}: {e}", spec.name)))?
                    .unwrap_owned();
                to_lua(lua, result.as_ref())
            })?,
        )?;
    }
    lua.globals().set("node", node)?;
    Ok(lua)
}

fn to_lua(lua: &Lua, value: &dyn PartialReflect) -> mlua::Result<mlua::Value> {
    if let Some(n) = value.try_downcast_ref::<f32>() {
        Ok(mlua::Value::Number(*n as f64))
    } else if let Some(b) = value.try_downcast_ref::<bool>() {
        Ok(mlua::Value::Boolean(*b))
    } else if let Some(s) = value.try_downcast_ref::<String>() {
        Ok(mlua::Value::String(lua.create_string(s)?))
    } else {
        Err(mlua::Error::runtime(format!("unsupported return type {}", value.reflect_type_path())))
    }
}

/// Loads a program's Lua into a runtime, ready to call.
pub fn load(lua: &Lua, program: &Program) -> mlua::Result<Function> {
    lua.load(emit(program)).set_name(&program.name).eval()
}

pub fn call(lua: &Lua, function: &Function, inputs: &[Value]) -> mlua::Result<Value> {
    let args: Vec<mlua::Value> = inputs
        .iter()
        .map(|v| {
            Ok(match v {
                Value::Number(n) => mlua::Value::Number(*n as f64),
                Value::Bool(b) => mlua::Value::Boolean(*b),
                Value::Text(t) => mlua::Value::String(lua.create_string(t)?),
            })
        })
        .collect::<mlua::Result<_>>()?;
    let result: mlua::Value = function.call(Variadic::from_iter(args))?;
    match result {
        mlua::Value::Number(n) => Ok(Value::Number(n as f32)),
        mlua::Value::Integer(n) => Ok(Value::Number(n as f32)),
        mlua::Value::Boolean(b) => Ok(Value::Bool(b)),
        mlua::Value::String(s) => Ok(Value::Text(s.to_str()?.to_string())),
        other => Err(mlua::Error::runtime(format!("unexpected result {}", other.type_name()))),
    }
}
