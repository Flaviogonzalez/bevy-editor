//! The Rust backend: the same IR, written out as plain Rust that calls the node functions.
//!
//! The code is built as a token tree with `quote` and formatted with `prettyplease`, so it is
//! always syntactically valid.

use proc_macro2::{Literal, TokenStream};
use quote::{format_ident, quote};

use crate::catalog::PinType;
use crate::ir::{Operand, Program};

fn ty(t: PinType) -> TokenStream {
    match t {
        PinType::Number => quote!(f32),
        PinType::Bool => quote!(bool),
        PinType::Text => quote!(String),
    }
}

fn operand(op: &Operand) -> TokenStream {
    match op {
        Operand::Input(i) => {
            let name = format_ident!("in{}", *i);
            quote!(#name)
        }
        Operand::Var(v) => {
            let name = format_ident!("v{}", *v);
            quote!(#name)
        }
        Operand::Number(n) if n.is_nan() => quote!(f32::NAN),
        Operand::Number(n) if *n == f32::INFINITY => quote!(f32::INFINITY),
        Operand::Number(n) if *n == f32::NEG_INFINITY => quote!(f32::NEG_INFINITY),
        Operand::Number(n) => {
            // Literals can't carry a sign, so negatives (including -0.0) are negated literals.
            let lit = Literal::f32_suffixed(n.abs());
            if n.is_sign_negative() { quote!((-#lit)) } else { quote!(#lit) }
        }
        Operand::Bool(b) => quote!(#b),
        Operand::Text(t) => quote!(String::from(#t)),
    }
}

/// One Rust function per program.
pub fn emit_function(program: &Program) -> TokenStream {
    let name = format_ident!("{}", program.name);
    let params = program.inputs.iter().enumerate().map(|(i, (_, t))| {
        let p = format_ident!("in{}", i);
        let t = ty(*t);
        quote!(#p: #t)
    });
    let ret = ty(program.output);
    let calls = program.calls.iter().map(|call| {
        let var = format_ident!("v{}", call.var);
        let node = format_ident!("{}", call.node);
        let args = call.args.iter().map(operand);
        quote!(let #var = crate::nodes::#node(#(#args),*);)
    });
    let result = operand(&program.result);
    quote! {
        pub fn #name(#(#params),*) -> #ret {
            #(#calls)*
            #result
        }
    }
}

/// A whole formatted module.
pub fn emit_module(programs: &[Program]) -> String {
    let functions = programs.iter().map(emit_function);
    let tokens = quote! {
        #![allow(clippy::all, unused_parens)]
        #(#functions)*
    };
    let file: syn::File = syn::parse2(tokens).expect("quote produces valid Rust");
    format!(
        "// Generated by `cargo run --example codegen`. Do not edit.\n\n{}",
        prettyplease::unparse(&file)
    )
}
