//! Writes `crates/vs_nodes/src/glam_nodes.rs`: the methods of Bevy's `Vec3` and `Quat` as nodes.
//!
//! It reads the source of the glam version `bevy_math` depends on, so the nodes are exactly what
//! that version offers, with its own documentation as their descriptions. A method becomes a
//! node when every input and its result are types pins carry (number, bool, vector, rotation)
//! and it's plain: public, safe, not generic, not behind a feature. Run it after updating Bevy
//! and review the diff:
//!
//! ```sh
//! cargo run -p gen_math
//! ```
//!
//! The file is checked in, so building the editor never needs this.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use quote::ToTokens;
use syn::{Attribute, FnArg, ImplItem, Item, Pat, ReturnType, Type};

/// One type whose methods become nodes.
struct Source {
    /// The type, as Bevy's prelude names it.
    ty: &'static str,
    /// Where glam defines it (the scalar version; the SIMD ones have the same methods).
    file: &'static str,
    category: &'static str,
    module: &'static str,
    /// The pin name for the value the method is called on.
    receiver: &'static str,
    /// Methods left out because a hand-written node already covers them, in friendlier units.
    covered: &'static [&'static str],
}

const SOURCES: &[Source] = &[
    Source {
        ty: "Vec3",
        file: "src/f32/vec3.rs",
        category: "Vector",
        module: "vec3",
        receiver: "v",
        covered: &["new", "splat"],
    },
    Source {
        ty: "Quat",
        file: "src/f32/scalar/quat.rs",
        category: "Rotation",
        module: "quat",
        receiver: "rotation",
        // Angles in degrees, and the same operations by name.
        covered: &["from_axis_angle", "mul_quat", "mul_vec3"],
    },
];

struct Node {
    doc: String,
    title: String,
    name: String,
    args: Vec<(String, &'static str)>,
    ret: &'static str,
    body: String,
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let (glam, version) = glam_dir(&root);
    let mut out = String::new();
    writeln!(out, "//! Methods of Bevy's math types as nodes. Generated by `tools/gen_math` from glam {version}:").unwrap();
    writeln!(out, "//! don't edit, run `cargo run -p gen_math` instead.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "nodes! {{").unwrap();
    writeln!(out, "    glam;").unwrap();
    let mut total = 0;
    for source in SOURCES {
        let path = glam.join(source.file);
        let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let file = syn::parse_file(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let nodes = methods(&file, source);
        total += nodes.len();
        writeln!(out, "    \"{}\" {} {{", source.category, source.module).unwrap();
        for node in &nodes {
            let args: Vec<String> = node.args.iter().map(|(n, t)| format!("{n}: {t}")).collect();
            writeln!(out, "        /// {}", node.doc).unwrap();
            writeln!(
                out,
                "        \"{}\" fn {}({}) -> {} {{ {} }}",
                node.title,
                node.name,
                args.join(", "),
                node.ret,
                node.body
            )
            .unwrap();
        }
        writeln!(out, "    }}").unwrap();
        println!("{}: {} methods", source.ty, nodes.len());
    }
    writeln!(out, "}}").unwrap();
    let target = root.join("crates/vs_nodes/src/glam_nodes.rs");
    std::fs::write(&target, out).unwrap();
    println!("wrote {total} nodes to {}", target.display());
}

/// The source directory and version of the glam `bevy_math` uses, from `cargo metadata`.
fn glam_dir(root: &Path) -> (PathBuf, String) {
    let output = Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--manifest-path"])
        .arg(root.join("Cargo.toml"))
        .output()
        .expect("cargo runs");
    assert!(output.status.success(), "cargo metadata failed: {}", String::from_utf8_lossy(&output.stderr));
    let meta: serde_json::Value = serde_json::from_slice(&output.stdout).expect("metadata is JSON");
    let packages = meta["packages"].as_array().unwrap();
    let package = |id: &str| packages.iter().find(|p| p["id"] == id).unwrap();
    let nodes = meta["resolve"]["nodes"].as_array().unwrap();
    let bevy_math = nodes
        .iter()
        .find(|n| package(n["id"].as_str().unwrap())["name"] == "bevy_math")
        .expect("bevy_math is a dependency");
    let glam_id = bevy_math["deps"]
        .as_array()
        .unwrap()
        .iter()
        .find(|d| d["name"] == "glam")
        .and_then(|d| d["pkg"].as_str())
        .expect("bevy_math depends on glam");
    let glam = package(glam_id);
    let manifest = PathBuf::from(glam["manifest_path"].as_str().unwrap());
    (manifest.parent().unwrap().to_path_buf(), glam["version"].as_str().unwrap().to_string())
}

/// A type pins carry, by the name the node uses.
fn pin_type(ty: &Type, this: &'static str) -> Option<&'static str> {
    let Type::Path(p) = ty else { return None };
    if p.qself.is_some() || p.path.segments.len() != 1 {
        return None;
    }
    match p.path.segments[0].ident.to_string().as_str() {
        "f32" => Some("f32"),
        "bool" => Some("bool"),
        "Self" => Some(this),
        "Vec3" => Some("Vec3"),
        "Quat" => Some("Quat"),
        _ => None,
    }
}

fn has_attr(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|a| a.path().is_ident(name))
}

/// The first paragraph of a doc comment, on one line, without rustdoc link brackets.
fn doc(attrs: &[Attribute]) -> String {
    let mut lines = Vec::new();
    for a in attrs {
        if !a.path().is_ident("doc") {
            continue;
        }
        let syn::Meta::NameValue(nv) = &a.meta else { continue };
        let syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) = &nv.value else { continue };
        let line = s.value().trim().to_string();
        if line.is_empty() {
            if !lines.is_empty() {
                break;
            }
            continue;
        }
        lines.push(line);
    }
    let text = lines.join(" ").split_whitespace().collect::<Vec<_>>().join(" ");
    // [`Self::length()`] → `Self::length()`; [link text](url) isn't used in these docs.
    text.replace("[`", "`").replace("`]", "`")
}

/// `length_squared` → `Length Squared`.
fn title(name: &str) -> String {
    name.split('_')
        .filter(|w| !w.is_empty())
        .map(|w| {
            if w == "nan" {
                return "NaN".to_string();
            }
            let mut c = w.chars();
            c.next().map(|f| f.to_uppercase().chain(c).collect::<String>()).unwrap_or_default()
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn methods(file: &syn::File, source: &Source) -> Vec<Node> {
    let mut out = Vec::new();
    for item in &file.items {
        let Item::Impl(imp) = item else { continue };
        if imp.trait_.is_some() || imp.self_ty.to_token_stream().to_string() != source.ty {
            continue;
        }
        for item in &imp.items {
            let ImplItem::Fn(f) = item else { continue };
            let sig = &f.sig;
            let name = sig.ident.to_string();
            let plain = matches!(f.vis, syn::Visibility::Public(_))
                && sig.unsafety.is_none()
                && sig.asyncness.is_none()
                && sig.generics.params.is_empty()
                && sig.variadic.is_none()
                && !has_attr(&f.attrs, "cfg")
                && !has_attr(&f.attrs, "deprecated")
                && !source.covered.contains(&name.as_str());
            if !plain {
                continue;
            }
            let ReturnType::Type(_, ret) = &sig.output else { continue };
            let Some(ret) = pin_type(ret, source.ty) else { continue };

            let mut receiver = false;
            let mut params: Vec<(String, &'static str)> = Vec::new();
            let mut fits = true;
            for input in &sig.inputs {
                match input {
                    FnArg::Receiver(r) if r.mutability.is_none() => receiver = true,
                    FnArg::Receiver(_) => fits = false,
                    FnArg::Typed(t) => match (&*t.pat, pin_type(&t.ty, source.ty)) {
                        (Pat::Ident(id), Some(ty)) => {
                            let n = id.ident.to_string();
                            // `rhs` reads as jargon on a pin.
                            params.push((if n == "rhs" { "other".into() } else { n }, ty));
                        }
                        _ => fits = false,
                    },
                }
            }
            if !fits {
                continue;
            }
            let call_args: Vec<&str> = params.iter().map(|(n, _)| n.as_str()).collect();
            let call_args = call_args.join(", ");
            let (args, body) = if receiver {
                let mut me = source.receiver.to_string();
                while params.iter().any(|(n, _)| *n == me) {
                    me.push('_');
                }
                let body = format!("{me}.{name}({call_args})");
                let mut args = vec![(me, source.ty)];
                args.extend(params);
                (args, body)
            } else {
                (params, format!("{}::{name}({call_args})", source.ty))
            };
            // The docs talk about `self` and `rhs`; the node's pins have other names.
            let me = args.first().filter(|_| receiver).map_or(source.ty.to_string(), |(n, _)| n.clone());
            let doc = doc(&f.attrs)
                .replace("`self`", &format!("`{me}`"))
                .replace("`rhs`", "`other`")
                .replace("`Self`", source.ty)
                .replace("Self::", &format!("{}::", source.ty));
            out.push(Node { doc, title: title(&name), name, args, ret, body });
        }
    }
    out
}
